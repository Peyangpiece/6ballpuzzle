#!/usr/bin/env node
// Prints a Markdown table of every runtime script in production load order
// with its size and the first line of its header comment.  Used to generate
// docs/ARCHITECTURE.generated.md (npm run docs:layers).
const fs = require("fs"), path = require("path");
const PUBLIC = path.join(__dirname, "..", "public");
const html = fs.readFileSync(path.join(PUBLIC, "index.html"), "utf8");
const files = JSON.parse(/var files=(\[[\s\S]*?\]);/.exec(html)[1]);
const GROUPS = [
  [/^app-0[1-7]\.js$/, "core: constants, physics planner, resolver, renderer"],
  [/^app-(08|09|10|14|15|16|17)\.js$/, "core: engine, assets, net, app shell"],
  [/^app-(pile-arc|clear-gap-collapse|floor-gap-invariant|clear-vacancy-priority|release-parity-settle)\.js$/, "clear / collapse corrections"],
  [/^app-(clear-all-ball-fx|gameover-garbage-fade)\.js$/, "presentation effects"],
  [/^app-(google-login|online-v2)\.js$/, "online"],
  [/^app-(menu-ui|brand-bgm|bgm-local|audio-volume-control|menu-volume-fix|rotate-sfx|instant-drop-sfx|position-lock-sfx)\.js$/, "menu / audio"],
  [/^app-garbage-/, "garbage (おじゃま) pipeline"],
  [/^app-ai-/, "AI opponent"],
  [/^app-runtime-performance/, "performance"],
  [/^app-(physics-safety-invariants|mass-motion-safety|contact-separation-v1)\.js$/, "safety invariants"],
  [/^app-(gravity-priority-v1|floor-bridge-collapse-v1|lattice-finalize-v2|coherent-collapse-v1|collapse-vertical-merge-v1|pile-motion-authority-v2)\.js$/, "collapse scheduling authorities"],
  [/^app-(wall-boundary|slope-upconvex|intentional-hexagon|rigidity-|reference-|no-upward-bounce|even-row|split-visual|motion-smoothness)/, "rigidity / split authorities (Nintendo reference)"],
  [/^controls-/, "input"],
  [/^app-switch-gamepad/, "input"]
];
function group(f) { for (const [re, g] of GROUPS) if (re.test(f)) return g; return "other"; }
function summary(src) {
  const m = /^\s*\/\*+\s*([^\n]*)\n(?:\s*\*\s*([^\n]*)\n)?/.exec(src) || /^\s*\/\/\s*([^\n]*)/.exec(src);
  if (!m) return "";
  let s = (m[1] || "").replace(/[=*]+/g, "").trim();
  if (!s && m[2]) s = m[2].replace(/[=*]+/g, "").trim();
  return s.slice(0, 110);
}
const rows = files.map((f, i) => {
  const src = fs.readFileSync(path.join(PUBLIC, f), "utf8");
  const wraps = [];
  if (/\bcreateEngine\s*=\s*function/.test(src)) wraps.push("createEngine");
  if (/\bhexPhysPlanGroup\s*=\s*function|basePlanGroup\s*=\s*hexPhysPlanGroup/.test(src)) wraps.push("hexPhysPlanGroup");
  if (/\bhexPhysResolveEvent\s*=\s*function|baseResolve\w*\s*=\s*hexPhysResolveEvent/.test(src)) wraps.push("hexPhysResolveEvent");
  const lines = src.split("\n").length;
  return `| ${i + 1} | \`${f}\` | ${group(f)} | ${lines} | ${wraps.join(", ") || ""} | ${summary(src).replace(/\|/g, "\\|")} |`;
});
console.log("# Runtime layer map (generated)\n");
console.log("Generated by `npm run docs:layers` from the loader array in `public/index.html`. Do not edit by hand.\n");
console.log("Scripts execute in this order in one shared global scope. A later layer that wraps `createEngine`, `hexPhysPlanGroup` or `hexPhysResolveEvent` takes precedence over earlier ones for that hook.\n");
console.log("| # | file | group | lines | wraps | header |");
console.log("| ---: | --- | --- | ---: | --- | --- |");
console.log(rows.join("\n"));
